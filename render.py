"""Render a scene into animated SVG files.

    .venv/bin/python render.py earth                  # colour, green and amber versions into out/
    .venv/bin/python render.py earth --modes color    # only the colour version
    .venv/bin/python render.py earth --frames 12      # quick low-frame draft
"""
from __future__ import annotations

import argparse
import importlib
import logging
import time
from pathlib import Path

from ascii.engine import (
    MONO_HUES,
    SIZE_BUDGET_BYTES,
    encode_svg,
    fit_color_map,
    fit_mono_map,
    mono_background,
    size_report,
    write_text_dump,
)

log = logging.getLogger("render")
MODES = ("color", *MONO_HUES)


def render_scene(name: str, modes: list[str], out_dir: Path, frames: int | None = None) -> list[Path]:
    unknown = [m for m in modes if m not in MODES]
    if unknown:
        raise SystemExit(f"unknown mode(s) {unknown}; choose from {', '.join(MODES)}")
    scene = importlib.import_module(f"ascii.scenes.{name}").make_scene()
    n = frames or scene.frames
    hero = round(scene.hero * n / scene.frames) % n

    started = time.perf_counter()
    pictures = [scene.render(k, n) for k in range(n)]
    static = scene.static()
    twinkles = scene.twinkles()
    log.info("%s: %d frames of %dx%d in %.1fs", name, n, scene.cols, scene.rows, time.perf_counter() - started)

    out_dir.mkdir(parents=True, exist_ok=True)
    layers = [*pictures, static] if static is not None else pictures
    written = []
    for mode in modes:
        if mode == "color":
            cmap, background = fit_color_map(layers, scene.max_colors), scene.style.background
        else:
            hue = MONO_HUES[mode]
            cmap, background = fit_mono_map(layers, hue, scene.mono_levels), mono_background(hue)
        svg = encode_svg(
            pictures, cmap, fps=scene.fps, style=scene.style, title=scene.title, background=background,
            static=static, twinkles=twinkles, hero=hero,
            description=f"{n} frames at {scene.fps:g} fps, generated by render.py ({name}, {mode})",
        )
        path = out_dir / f"{name}-{mode}.svg"
        path.write_text(svg, encoding="utf-8")
        raw, packed = size_report(svg)
        flag = "  <-- over budget" if raw > SIZE_BUDGET_BYTES else ""
        log.info("  %s: %d colours, %.0f KB raw, %.0f KB gzip%s",
                 path, len(cmap.colors), raw / 1024, packed / 1024, flag)
        written.append(path)
    write_text_dump(pictures, out_dir / f"{name}-frames.txt")
    return written


def main(argv: list[str] | None = None) -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("scene", help="module name in ascii/scenes, e.g. earth")
    parser.add_argument("--modes", default=",".join(MODES), help=f"comma-separated subset of {', '.join(MODES)}")
    parser.add_argument("--frames", type=int, help="override the frame count (drafts)")
    parser.add_argument("--out", type=Path, default=Path("out"))
    args = parser.parse_args(argv)
    logging.basicConfig(level=logging.INFO, format="%(message)s")
    render_scene(args.scene, [m.strip() for m in args.modes.split(",") if m.strip()], args.out, args.frames)


if __name__ == "__main__":
    main()
